using ECommerceStore.Models;
using ECommerceStore.Repository;

namespace ECommerceStore.Services;

public class ProductService
{
    private readonly ProductRepository _repository;

    public ProductService(ProductRepository repository)
    {
        _repository = repository;
    }

    public async Task AddProductAsync(Product product)
    {
        if (string.IsNullOrWhiteSpace(product.ProductName))
            throw new ArgumentException("Product name is required.");
        if (product.Price < 0)
            throw new ArgumentException("Price cannot be negative.");
        if (product.StockQuantity < 0)
            throw new ArgumentException("Stock quantity cannot be negative.");

        await _repository.AddProductAsync(product);
    }
    public async Task<OrderInvoice> PlaceOrderAsync(int customerId, int productId, int quantity)
    {
        if (customerId <= 0)
            throw new ArgumentException("Customer ID must be greater than zero.");
        if (productId <= 0)
            throw new ArgumentException("Product ID must be greater than zero.");
        if (quantity <= 0)
            throw new ArgumentException("Order quantity must be greater than zero.");

        // Forward the call and return the invoice generated by the repository
        return await _repository.PlaceOrderAsync(customerId, productId, quantity);
    }

    public Task<List<Product>> GetAllProductsAsync()
    {
        return _repository.GetAllProductsAsync();
    }

    public async Task<Product?> GetProductByIdAsync(int id)
    {
        if (id <= 0)
            throw new ArgumentException("Product ID must be greater than zero.");
        return await _repository.GetProductByIdAsync(id);
    }
}